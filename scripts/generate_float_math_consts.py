#!/usr/bin/env python3
"""Write math/src/float_math_consts.h: the constants of proven_math's integer path (RFC-0056).

Each constant is a mantissa of 32-bit limbs, least significant first, with its top bit set, and
the binary exponent of its last bit: value = M * 2^E, rounded toward zero (the integer path
counts that as part of its error bound). 2/pi is given as its fraction bits from the binary
point, for the Payne-Hanek reduction. Needs mpmath. Run from the project root:
    python3 scripts/generate_float_math_consts.py > math/src/float_math_consts.h
"""
import mpmath

LIMBS = 32            # 1,024 bits: past the integer path's largest precision (768) and margin
TWO_OVER_PI_LIMBS = 72  # 2,304 fraction bits: 1,024 for the exponent range, the rest for precision

mpmath.mp.prec = 4000


def mantissa(x, limbs):
    bits = 32 * limbs
    e = int(mpmath.floor(mpmath.log(x, 2))) + 1 - bits
    m = int(mpmath.floor(x / mpmath.mpf(2) ** e))
    assert m >> (bits - 1) == 1 and m >> bits == 0
    return m, e


def limbs_of(m, limbs):
    return [(m >> (32 * i)) & 0xffffffff for i in range(limbs)]


def emit(name, x, limbs):
    m, e = mantissa(x, limbs)
    out = [f"/* {name}: M * 2^{e} */", f"#define {name}_EXP ({e})",
           f"static const proven_u32 {name}[{limbs}] = {{"]
    ls = limbs_of(m, limbs)
    for i in range(0, limbs, 6):
        out.append("    " + ", ".join(f"0x{v:08x}u" for v in ls[i:i + 6]) + ",")
    out.append("};")
    return "\n".join(out)


def emit_fraction(name, x, limbs):
    """The first 32*limbs bits after the binary point, most significant limb first."""
    f = x - mpmath.floor(x)
    m = int(mpmath.floor(f * mpmath.mpf(2) ** (32 * limbs)))
    ls = [(m >> (32 * (limbs - 1 - i))) & 0xffffffff for i in range(limbs)]
    out = [f"/* {name}: the fraction bits of the constant, most significant limb first */",
           f"static const proven_u32 {name}[{limbs}] = {{"]
    for i in range(0, limbs, 6):
        out.append("    " + ", ".join(f"0x{v:08x}u" for v in ls[i:i + 6]) + ",")
    out.append("};")
    return "\n".join(out)


print("""#ifndef PROVEN_FLOAT_MATH_CONSTS_H
#define PROVEN_FLOAT_MATH_CONSTS_H

/* Constants of proven_math's integer path (RFC-0056), generated by
 * scripts/generate_float_math_consts.py with mpmath at 4,000 bits; do not edit. A mantissa is
 * 32-bit limbs, least significant first, top bit set: value = M * 2^NAME_EXP, rounded toward
 * zero. */

#include "proven/types.h"

#define FM_CONST_LIMBS %d
""" % LIMBS)
print(emit("FM_LN2", mpmath.log(2), LIMBS))
print()
print(emit("FM_PI_2", mpmath.pi / 2, LIMBS))
print()
print(emit("FM_INV_LN2", 1 / mpmath.log(2), 2))
print()
TAB = 6               # limbs of the tables of the first Ziv level (192 bits)


def entry(x):
    """{limbs, exponent, sign}: |x| = M * 2^e with M of TAB limbs, top bit set; 0 for x = 0."""
    if x == 0:
        return "{ {" + ", ".join(["0u"] * TAB) + "}, 0, 0 }"
    neg = x < 0
    m, e = mantissa(abs(x), TAB)
    ls = limbs_of(m, TAB)
    return "{ {" + ", ".join(f"0x{v:08x}u" for v in ls) + "}, %d, %d }" % (e, 1 if neg else 0)


def table(name, values, comment):
    out = [f"/* {comment} */", f"static const fm_tab_t {name}[{len(values)}] = {{"]
    for v in values:
        out.append("    " + entry(v) + ",")
    out.append("};")
    return "\n".join(out)


print("#define FM_TAB_LIMBS %d" % TAB)
print("typedef struct { proven_u32 d[%d]; int e; int neg; } fm_tab_t;" % TAB)
print()
print(table("FM_EXP2_64", [mpmath.mpf(2) ** (mpmath.mpf(j) / 64) for j in range(64)], "2^(j/64), j = 0 .. 63"))
print()
R = [int(mpmath.nint(mpmath.mpf(2) ** 16 / (mpmath.mpf(0.75) + (mpmath.mpf(j) + mpmath.mpf(0.5)) / 256))) for j in range(192)]
print("/* R_j = round(2^16 / c_j), c_j = 0.75 + (j + 1/2) / 256: m R_j / 2^16 is within 2^-8 of 1 for m in [0.75 + j/256, +1/256) */")
print("static const proven_u32 FM_LOG_R[192] = {")
for i in range(0, 192, 12):
    print("    " + ", ".join(f"{v}u" for v in R[i:i + 12]) + ",")
print("};")
print(table("FM_LOG_RL", [-mpmath.log(mpmath.mpf(r) / 2 ** 16) for r in R], "-log(R_j / 2^16), j = 0 .. 191"))
print()
print(table("FM_SIN_64", [mpmath.sin(mpmath.mpf(j) / 64) for j in range(53)], "sin(j/64), j = 0 .. 52"))
print()
print(table("FM_COS_64", [mpmath.cos(mpmath.mpf(j) / 64) for j in range(53)], "cos(j/64), j = 0 .. 52"))
print()
print(table("FM_ATAN_64", [mpmath.atan(mpmath.mpf(j) / 64) for j in range(65)], "atan(j/64), j = 0 .. 64"))
print()
print(table("FM_INV_FACT", [1 / mpmath.factorial(k) for k in range(32)], "1/k!, k = 0 .. 31"))
print()
print(table("FM_INV_K", [mpmath.mpf(0)] + [1 / mpmath.mpf(k) for k in range(1, 48)], "1/k, k = 1 .. 47 (0 at 0)"))
print()
def fixed(name, values, comment):
    """Magnitudes as fixed point: floor(|v| 2^(32 TAB - 8)) in TAB limbs, least significant first."""
    out = [f"/* {comment}: |v| 2^{32 * TAB - 8}, truncated */", f"static const proven_u32 {name}[{len(values)}][{TAB}] = {{"]
    for v in values:
        m = int(mpmath.floor(abs(v) * mpmath.mpf(2) ** (32 * TAB - 8)))
        out.append("    {" + ", ".join(f"0x{x:08x}u" for x in limbs_of(m, TAB)) + "},")
    out.append("};")
    return "\n".join(out)


print(fixed("FM_INV_FACT_FX", [1 / mpmath.factorial(k) for k in range(32)], "1/k!, k = 0 .. 31"))
print()
print(fixed("FM_INV_K_FX", [mpmath.mpf(0)] + [1 / mpmath.mpf(k) for k in range(1, 48)], "1/k, k = 1 .. 47 (0 at 0)"))
print()
print("#define FM_TWO_OVER_PI_LIMBS %d" % TWO_OVER_PI_LIMBS)
print(emit_fraction("FM_TWO_OVER_PI", 2 / mpmath.pi, TWO_OVER_PI_LIMBS))
print()
print("#endif /* PROVEN_FLOAT_MATH_CONSTS_H */")
